"""data_quality/windows.py — the declared register of KNOWN DATA-QUALITY
WINDOWS: date ranges over which a published artifact is known to carry a
defect that was measured, ruled on, and deliberately left in place.

**Why this exists as code and not as a tracked issue.** A GitHub issue is a
unit of *work* — it is opened to be closed, it is counted in backlog health,
and once closed it stops being read. A known-defect window is the opposite:
it is a permanent *property of data already on S3*, it outlives every fix,
and its whole value is that a consumer reading those dates can find it. The
unsettled-bar window below was first recorded as
``alpha-engine-config-I11367`` and moved here for exactly that reason
(Brian, 2026-09-22): the artifact tracking this class must be permanent and
easy to reach, not a row in a queue.

**Source of truth.** This module is authoritative. ``DATA_QUALITY_WINDOWS.md``
at the repo root is a RENDERED view of it, regenerated by
``data_quality/gen_windows_md.py --write`` and drift-checked in CI by
``tests/test_data_quality_windows_contract.py``. This mirrors the
``features/registry.py::CATALOG`` -> ``features/SCHEMA.md`` §3 arrangement,
which exists because a hand-maintained table drifted from the code once in
production (the ``avg_volume_20d`` units incident, SCHEMA.md §1) — the same
reason applies here and the same shape answers it.

**What belongs here.** A window is admitted when ALL of the following hold:

1. The defect is **measured**, not suspected, and the measurement has a
   durable artifact behind it (``evidence``).
2. The affected data is **already published** and will stay published —
   a defect caught before anything landed is a bug, not a window.
3. A **disposition has been ruled**: either the data is being left as-is, or
   a remediation is scheduled. "We should probably look at this" is not a
   disposition and does not belong here.

A defect still being fixed forward is NOT a window until the forward fix has
landed and the historical residue is what remains. Use the backlog for the
fix; use this register for what the fix cannot reach.

**Consuming this register.** ``overlapping(artifact, start, end)`` answers
"does any declared window touch the dates I am about to read". A consumer
that grades a result over historical data is expected to call it and either
refuse or attach the caveat to its output, rather than relying on a human
having read the Markdown.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date

__all__ = ["QualityWindow", "WINDOWS", "overlapping", "window_by_id"]


#: A window's disposition — what was RULED about the affected data, not what
#: is planned for the code. ``no_remediation`` means the data stays as it is.
#: ``remediation_pending`` means a rewrite is scheduled and named in
#: ``reexam_trigger``. ``remediated`` means the affected range has been
#: rewritten and the window is kept for the historical record only.
DISPOSITIONS = ("no_remediation", "remediation_pending", "remediated")


@dataclass(frozen=True)
class QualityWindow:
    """One declared known-defect window over published data.

    ``last_affected`` is ``None`` for a window whose closing date is not yet
    established — never a far-future sentinel, which reads as a real date to
    every consumer that does not know the convention.
    """

    window_id: str
    #: S3 key templates this window applies to, written exactly as the
    #: producing code writes them (``{date}`` / ``{trading_day}`` intact).
    artifacts: tuple[str, ...]
    first_affected: date
    last_affected: date | None
    #: One line. What is wrong with the data, in the reader's terms.
    defect: str
    #: Measured magnitudes, ``{label: value}``. Every entry is a number that
    #: was observed, never an estimate or a tolerance.
    measured: dict[str, str]
    #: Where the measurement can be re-read. An S3 key, a report, an artifact.
    evidence: str
    disposition: str
    ruled_by: str
    ruled_on: date
    #: The CONDITION that re-opens the disposition. Never a date — a window
    #: whose re-exam is a calendar entry gets re-read to produce the same
    #: answer until someone stops reading it.
    reexam_trigger: str
    #: Free-form detail: affected readers, what the forward fix was, what a
    #: remediation would have to do. Rendered as prose under the table.
    notes: tuple[str, ...] = field(default_factory=tuple)

    def covers(self, day: date) -> bool:
        """True when ``day`` falls inside this window."""
        if day < self.first_affected:
            return False
        return self.last_affected is None or day <= self.last_affected


