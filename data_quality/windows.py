def window_by_id(window_id: str) -> QualityWindow:
    """Return the window with ``window_id``, or raise ``KeyError``.

    Raises rather than returning ``None``: a caller naming a window that does
    not exist has a typo or a stale reference, and silently returning "no
    known defect" is the failure this register exists to prevent.
    """
    for window in WINDOWS:
        if window.window_id == window_id:
            return window
    raise KeyError(
        f"no declared quality window {window_id!r} — "
        f"known: {sorted(w.window_id for w in WINDOWS)}"
    )


def overlapping(
    artifact: str, start: date, end: date
) -> tuple[QualityWindow, ...]:
    """Windows touching ``artifact`` anywhere in ``[start, end]``.

    ``artifact`` is matched against the declared key TEMPLATES literally, so
    callers pass the template (``features/{date}/technical.parquet``), not a
    resolved key. Matching resolved keys would need a parser per template
    shape and would silently miss the ones it could not parse.
    """
    if end < start:
        raise ValueError(f"end {end} precedes start {start}")
    hits = []
    for window in WINDOWS:
        if artifact not in window.artifacts:
            continue
        if window.first_affected > end:
            continue
        if window.last_affected is not None and window.last_affected < start:
            continue
        hits.append(window)
    return tuple(hits)
