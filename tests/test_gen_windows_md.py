"""Behaviour tests for data_quality/gen_windows_md.py (render + --write/--check)."""

from __future__ import annotations

from datetime import date
from pathlib import Path

import pytest

from data_quality import gen_windows_md
from data_quality.windows import QualityWindow


def _window(**overrides: object) -> QualityWindow:
    base: dict[str, object] = {
        "window_id": "example-window",
        "artifacts": ("a/{date}.parquet", "b/{date}.parquet"),
        "first_affected": date(2026, 1, 2),
        "last_affected": date(2026, 1, 9),
        "defect": "Example defect.",
        "measured": {"rows": "12"},
        "evidence": "s3://example/evidence.json",
        "disposition": "no_remediation",
        "ruled_by": "Example Owner",
        "ruled_on": date(2026, 2, 3),
        "reexam_trigger": "When the example changes.",
        "notes": ("First note.", "Second note."),
    }
    base.update(overrides)
    return QualityWindow(**base)  # type: ignore[arg-type]  # pyright: ignore[reportArgumentType]


def test_render_window_full_layout() -> None:
    text = gen_windows_md.render_window(_window())
    assert text.split("\n") == [
        "## `example-window`",
        "",
        "Example defect.",
        "",
        "| | |",
        "|---|---|",
        "| **Affected dates** | 2026-01-02 through 2026-01-09 |",
        "| **Artifacts** | `a/{date}.parquet`<br>`b/{date}.parquet` |",
        "| **rows** | 12 |",
        "| **Evidence** | s3://example/evidence.json |",
        "| **Disposition** | `no_remediation` — ruled by Example Owner on 2026-02-03 |",
        "| **Re-exam trigger** | When the example changes. |",
        "",
        "- First note.",
        "- Second note.",
        "",
    ]


def test_render_window_open_ended_and_no_notes() -> None:
    # Mutation guarded: rendering a None last_affected as "None" instead of "open".
    text = gen_windows_md.render_window(_window(last_affected=None, notes=()))
    assert "| **Affected dates** | 2026-01-02 through open |" in text
    assert "None" not in text
    assert "- " not in text
    assert text.endswith("|\n")


def test_render_window_measured_order_preserved() -> None:
    text = gen_windows_md.render_window(_window(measured={"zeta": "1", "alpha": "2"}))
    assert text.index("**zeta**") < text.index("**alpha**")


def test_render_joins_windows_after_preamble(monkeypatch: pytest.MonkeyPatch) -> None:
    w1 = _window(window_id="first")
    w2 = _window(window_id="second")
    monkeypatch.setattr(gen_windows_md, "WINDOWS", (w1, w2))
    text = gen_windows_md.render()
    assert text.startswith("<!-- GENERATED by data_quality/gen_windows_md.py")
    assert "# Known data-quality windows" in text
    assert text.index("## `first`") < text.index("## `second`")
    assert text.endswith(gen_windows_md.render_window(w2))


def test_render_empty_register_says_so(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(gen_windows_md, "WINDOWS", ())
    text = gen_windows_md.render()
    assert text.endswith("_No windows are currently declared._\n")
    assert "## `" not in text


def test_main_default_prints_render(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    monkeypatch.setattr(gen_windows_md, "WINDOWS", (_window(),))
    assert gen_windows_md.main([]) == 0
    out = capsys.readouterr().out
    assert out == gen_windows_md.render() + "\n"


def test_main_write_then_check_ok(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    target = tmp_path / "DATA_QUALITY_WINDOWS.md"
    monkeypatch.setattr(gen_windows_md, "WINDOWS_MD", target)
    monkeypatch.setattr(gen_windows_md, "WINDOWS", (_window(),))
    assert gen_windows_md.main(["--write"]) == 0
    assert target.read_text(encoding="utf-8") == gen_windows_md.render()
    assert "Wrote" in capsys.readouterr().out
    assert gen_windows_md.main(["--check"]) == 0
    assert "matches the register. OK." in capsys.readouterr().out


def test_main_check_detects_drift(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # Mutation guarded: --check returning 0 when the file differs from a fresh render.
    target = tmp_path / "DATA_QUALITY_WINDOWS.md"
    target.write_text("stale\n", encoding="utf-8")
    monkeypatch.setattr(gen_windows_md, "WINDOWS_MD", target)
    monkeypatch.setattr(gen_windows_md, "WINDOWS", (_window(),))
    assert gen_windows_md.main(["--check"]) == 1
    err = capsys.readouterr().err
    assert err.startswith("DRIFT:")
    assert target.read_text(encoding="utf-8") == "stale\n"


def test_main_check_missing_file_fails(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    monkeypatch.setattr(gen_windows_md, "WINDOWS_MD", tmp_path / "absent.md")
    assert gen_windows_md.main(["--check"]) == 1
    assert "MISSING:" in capsys.readouterr().err


def test_main_write_takes_precedence_over_check(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    target = tmp_path / "out.md"
    monkeypatch.setattr(gen_windows_md, "WINDOWS_MD", target)
    monkeypatch.setattr(gen_windows_md, "WINDOWS", ())
    assert gen_windows_md.main(["--check", "--write"]) == 0
    assert target.exists()
